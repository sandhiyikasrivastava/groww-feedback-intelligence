"""Produce the deliverable artefacts under ``docs/``.

Runs the real pipeline over the collected dataset, then writes:

* ``docs/weekly_product_pulse.md``
* ``docs/customer_fee_explanation.md``
* ``docs/sources.md``
* ``docs/test_results.md`` (only with ``--with-tests``)
* ``docs/evidence/documentation_append.md``
* ``docs/evidence/email_draft.md``

The documentation append and the email draft go through the **same approval
gate** as the app: a request is created, approved with an explicit decision,
and only then executed.  Without Notion/Gmail credentials the executions are
simulated and every artefact says so.

    python scripts/generate_artifacts.py
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from datetime import date
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from groww_intel.approvals import (  # noqa: E402
    ApprovalStore,
    build_documentation_payload,
    render_documentation_markdown,
)
from groww_intel.config import DOCS_DIR, ensure_dirs  # noqa: E402
from groww_intel.integrations import (  # noqa: E402
    get_documentation_appender,
    get_email_drafter,
)
from groww_intel.llm import LLMClient  # noqa: E402
from groww_intel.pipeline import run_pipeline  # noqa: E402

EMAIL_SUBJECT = "Weekly Product Pulse + Customer Clarification — Groww"
AS_OF = date(2026, 10, 21)
WEEKS = 12
COLLECTED = PROJECT_ROOT / "data" / "collected" / "groww_appstore_reviews.csv"


def write_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"wrote {path.relative_to(PROJECT_ROOT)}")


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the deliverable artefacts")
    parser.add_argument("--csv", default=str(COLLECTED))
    parser.add_argument("--with-tests", action="store_true")
    parser.add_argument(
        "--llm-themes",
        action="store_true",
        help="Discover themes with the LLM (slow, rate-limit sensitive). "
        "By default the fast mode is used: rule-based themes + LLM-written reports.",
    )
    args = parser.parse_args()

    ensure_dirs()
    client = LLMClient()
    result = run_pipeline(
        args.csv,
        weeks=WEEKS,
        as_of=AS_OF,
        client=client,
        use_llm_themes=args.llm_themes,
    )

    # ---------------------------------------------------------------- pulse
    pulse = result.pulse
    pulse_md = [
        f"# {pulse.title}",
        "",
        f"- **Review window:** {result.review_date_range}",
        f"- **Reviews analysed:** {len(result.reviews)} (accepted from "
        f"{result.validation.rows_read} rows; {result.validation.excluded} excluded, "
        f"{result.validation.duplicates_removed} duplicates removed)",
        f"- **Generated by:** themes: "
        f"{'LLM' if result.analysis.mode.value == 'llm' else 'documented keyword taxonomy'}; "
        f"reports: {'LLM (' + client.describe() + ')' if pulse.mode.value == 'llm' else 'deterministic composer'}",
        f"- **Word count:** {pulse.word_count} / 250",
        f"- **Data source:** {result.validation.file_name} — Apple App Store customer reviews "
        f"(India storefront), public RSS feed",
        "",
        "---",
        "",
        pulse.body_markdown,
        "",
        "---",
        "",
        "### Recommendations in detail",
        "",
    ]
    for index, rec in enumerate(pulse.recommendations, start=1):
        pulse_md += [
            f"#### {index}. {rec.title}",
            "",
            f"- **Problem addressed:** {rec.problem}",
            f"- **Proposed intervention:** {rec.intervention}",
            f"- **Measurable outcome to track:** {rec.measurable_outcome}",
            "",
        ]
    if pulse.warnings:
        pulse_md += ["### Warnings", ""] + [f"- {w}" for w in pulse.warnings] + [""]
    write_text(DOCS_DIR / "weekly_product_pulse.md", "\n".join(pulse_md))

    # ---------------------------------------------------------- explanation
    explanation = result.explanation
    explanation_md = [
        f"# {explanation.title}",
        "",
        f"**Customer-facing snippet · {len(explanation.bullets)} bullets · "
        f"Last checked: {explanation.last_checked.isoformat() if explanation.last_checked else 'n/a'}**",
        "",
    ]
    explanation_md += [f"- {bullet}" for bullet in explanation.bullets]
    explanation_md += ["", "### Verified official sources", ""]
    explanation_md += [f"{i}. {link}" for i, link in enumerate(explanation.source_links, start=1)]
    if explanation.excluded_claims:
        explanation_md += ["", "### Claims excluded (could not be verified)", ""]
        explanation_md += [f"- {claim}" for claim in explanation.excluded_claims]
    if explanation.warnings:
        explanation_md += ["", "### Notes", ""] + [f"- {w}" for w in explanation.warnings]
    write_text(DOCS_DIR / "customer_fee_explanation.md", "\n".join(explanation_md) + "\n")

    # ---------------------------------------------------------------- sources
    verification = result.verification
    sources_md = [
        "# Official sources used for fee verification",
        "",
        f"**Last checked: {verification.last_checked.isoformat() if verification.last_checked else 'n/a'}**",
        "",
        "| # | Source | URL | Fetch | Facts verified |",
        "|---|--------|-----|-------|-----------------|",
    ]
    for index, source in enumerate(verification.sources, start=1):
        sources_md.append(
            f"| {index} | {source.title} | {source.url} | {source.fetch_status} | "
            f"{', '.join(source.facts_verified) or '—'} |"
        )
    sources_md += ["", "## Fee facts and their verification", "",
                   "| Fact | Value | Status | Source |", "|------|-------|--------|--------|"]
    for fact in verification.facts:
        sources_md.append(
            f"| {fact.label} | {fact.value} | **{fact.confidence}** | {fact.source_url} |"
        )
    if verification.unverified_claims:
        sources_md += ["", "## Unverified (excluded from the customer explanation)", ""]
        sources_md += [f"- {claim}" for claim in verification.unverified_claims]
    sources_md += [
        "",
        "## Notes",
        "",
        "- All URLs are first-party `groww.in` pages fetched live by "
        "`groww_intel/sources.py`; no blogs or third-party claims are used.",
        "- A fact is reported as verified only when its wording was found in the "
        "fetched page text (token check, whitespace-insensitive).",
        "",
    ]
    write_text(DOCS_DIR / "sources.md", "\n".join(sources_md))

    # ------------------------------------------- approval-gated integrations
    store = ApprovalStore()
    doc_choice = get_documentation_appender()
    mail_choice = get_email_drafter()

    issue = result.fee_result.selected
    supporting = (
        [f"{rid} — {result.validation.file_name}" for rid in issue.supporting_review_ids]
        if issue
        else []
    )
    record = build_documentation_payload(
        pulse_body=pulse.body_markdown,
        fee_issue=(
            f"{issue.label} — {len(issue.supporting_review_ids)} supporting reviews in "
            f"{issue.product_area.value}, {issue.distinct_weeks} distinct weeks, "
            f"{issue.explicit_mentions} explicit fee mentions"
            if issue
            else (result.fee_result.limitation_note or "No recurring fee issue identified")
        ),
        explanation_bullets=explanation.bullets,
        source_links=explanation.source_links,
        top_themes=pulse.leading_themes,
        review_date_range=result.review_date_range,
        reviews_analyzed=len(result.reviews),
        supporting_evidence=supporting,
        entry_date=AS_OF,
    )
    doc_content = render_documentation_markdown(record)

    doc_request = store.create_request(
        action="documentation_append",
        destination="Notion MCP server (https://mcp.notion.com/mcp)"
        if not doc_choice.simulated
        else "Simulated documentation service (local JSONL file)",
        content=doc_content,
        summary=f"Weekly product pulse ({result.review_date_range})",
    )
    store.approve(doc_request.request_id, decided_by="artifact-generator", note="Approved in script")
    doc_request = store.get(doc_request.request_id)
    store.assert_executable(doc_request, doc_content)
    doc_receipt = doc_choice.service.append(record, doc_content)
    store.record_execution(doc_request, doc_receipt)
    record.execution_status = doc_receipt.status

    email_body = (
        f"INTERNAL — Weekly Product Pulse\n\n{pulse.body_markdown}\n\n"
        f"{'-' * 60}\nCUSTOMER-FACING FEE EXPLANATION (reusable support snippet)\n\n"
        + "\n".join(f"- {bullet}" for bullet in explanation.bullets)
        + "\n\nVerified official sources (last checked: "
        + (explanation.last_checked.isoformat() if explanation.last_checked else "n/a")
        + "):\n"
        + "\n".join(f"- {link}" for link in explanation.source_links)
        + "\n"
    )
    mail_request = store.create_request(
        action="email_draft",
        destination="Gmail (MCP)" if not mail_choice.simulated else "Simulated Gmail draft service (local JSONL file)",
        content=email_body,
        summary=EMAIL_SUBJECT,
    )
    store.approve(mail_request.request_id, decided_by="artifact-generator", note="Approved in script")
    mail_request = store.get(mail_request.request_id)
    store.assert_executable(mail_request, email_body)
    mail_receipt = mail_choice.service.create_draft(EMAIL_SUBJECT, email_body, recipient=None)
    store.record_execution(mail_request, mail_receipt)

    # --------------------------------------------------------- evidence docs
    write_text(
        DOCS_DIR / "evidence" / "documentation_append.md",
        "\n".join(
            [
                "# Evidence — append to the documentation service",
                "",
                f"- **Action:** append a new entry (nothing is overwritten)",
                f"- **Destination:** {doc_request.destination}",
                f"- **Service:** {doc_choice.name}",
                f"- **Simulated:** {doc_receipt.simulated}",
                f"- **Execution status:** **{doc_receipt.status}**",
                f"- **External id:** {doc_receipt.external_id}",
                f"- **Approval request:** `{doc_request.request_id}` (approved by "
                f"{doc_request.decided_by})",
                f"- **Content hash:** `{doc_request.content_hash}`",
                "",
                "## Payload appended",
                "",
                "```markdown",
                doc_content,
                "```",
                "",
                "## Receipt",
                "",
                "```json",
                json.dumps(doc_receipt.model_dump(mode="json"), indent=2, ensure_ascii=False),
                "```",
                "",
            ]
        ),
    )

    write_text(
        DOCS_DIR / "evidence" / "email_draft.md",
        "\n".join(
            [
                "# Evidence — email draft",
                "",
                f"- **Action:** create a draft (**never sent**)",
                f"- **Subject:** {EMAIL_SUBJECT}",
                f"- **Recipient:** (blank — no recipient was supplied, and none was invented)",
                f"- **Destination:** {mail_request.destination}",
                f"- **Service:** {mail_choice.name}",
                f"- **Simulated:** {mail_receipt.simulated}",
                f"- **Execution status:** **{mail_receipt.status}**",
                f"- **External id:** {mail_receipt.external_id}",
                f"- **Approval request:** `{mail_request.request_id}` (approved by "
                f"{mail_request.decided_by})",
                "",
                "## Draft body",
                "",
                "```markdown",
                email_body,
                "```",
                "",
                "## Receipt",
                "",
                "```json",
                json.dumps(mail_receipt.model_dump(mode="json"), indent=2, ensure_ascii=False),
                "```",
                "",
            ]
        ),
    )

    # ------------------------------------------------------------ test report
    if args.with_tests:
        completed = subprocess.run(
            [sys.executable, "-m", "pytest", "tests", "-q", "--tb=short"],
            cwd=PROJECT_ROOT,
            capture_output=True,
            text=True,
        )
        output = (completed.stdout or "") + (completed.stderr or "")
        write_text(
            DOCS_DIR / "test_results.md",
            "\n".join(
                [
                    "# Automated test results",
                    "",
                    f"- **Command:** `python -m pytest tests -q`",
                    f"- **Exit code:** {completed.returncode}",
                    f"- **Date:** {date.today().isoformat()}",
                    "",
                    "```text",
                    output.strip(),
                    "```",
                    "",
                ]
            ),
        )

    print("\n--- summary ---")
    print(f"reviews analysed      : {len(result.reviews)}")
    print(f"themes                : {len(result.analysis.themes)}")
    print(f"fee issue             : {result.fee_result.selected.label if result.fee_result.selected else 'none'}")
    print(f"documentation append  : {doc_receipt.status}")
    print(f"email draft           : {mail_receipt.status}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
